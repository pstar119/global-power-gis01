-- 阶段28：移除阶段21 的电力网络**仿真数据**。
--
-- 背景：`substations` / `transmission_lines` 两张表中的全部内容，是阶段21 由
-- `003_seed_demo_grid.sql` 灌入的演示数据（6 个人工设定的枢纽 × 随机生成的点与线），
-- 当时只用来验证「多图层渲染 + 显隐联动 + 电压分级样式」这条链路能不能通。
-- 阶段28 起改用真实 OSM 数据，这些仿真点留在图上只会造成视觉污染，
-- 更糟的是会让人误以为它们是真实设施。
--
-- 为什么用 DELETE 而不是 DROP TABLE：
--   表结构与索引定义在 `001_init.sql`，前端 MapPage 的 SELECT 也依赖它们；
--   这里只清数据，表必须保留。清空后图层会渲染为空 —— 这是**有意的过渡状态**，
--   待真实的 OSM 切片接入后即有数据。
--
-- 为什么可以无条件 DELETE（没有 WHERE）：
--   这两张表里**从来只有**仿真数据（见上），真实数据一定是在本迁移之后才写入的。
--   因此无条件清空是安全的，而且天然幂等 —— 重复执行不会出错、也不会有副作用。
--   对「已有库」（v3 已应用）和「全新库」（v3 不再执行）两条路径结果一致。
DELETE FROM substations;
DELETE FROM transmission_lines;
