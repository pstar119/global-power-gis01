-- 阶段50-A：**移除** GEM 的 SQLite 通道（改建为 pmtiles 数据包）
--
-- ‼️ 为什么要删而不是留着：
--    阶段48-A 把 GEM 煤炭数据放进了本库（gem_coal_plants，14,509 机组级行）。
--    但阶段50 决定改成**可下载的 pmtiles 数据包**，理由是：
--      ① 安装包体积 —— 光煤炭就吃掉了 6.10 MB 种子库（安装包 +0.82 MB），
--         扩到三类电源（33,790 机组）会直接顶破 50 MB 红线；
--      ② 下载管线（packs.rs）**只接受 .pmtiles**，做不成 .db 数据包；
--      ③ 两套通道并存必然有人读错表，维护成本高。
--    ⇒ 保留这张表等于保留一条**永远不会再被写入**的死通道，
--      且前端一旦漏改就会读到过期数据（这类 bug 不报错，最难查）。
--
-- ⚠️ 本迁移是**破坏性**的：它与「前端停止读该表 + 改由数据包驱动」必须
--    在同一个提交里落地。顺序错了会导致用户一开 GEM 开关就查询不存在的表。
--
-- ⚠️ 数据本身不会丢：同样的内容已经包含在 gem-plants.pmtiles 数据包里
--    （三类电源、复合键去重、电站级聚合），由前端在数据包安装后加载。
--    所以这是一次「通道迁移」，不是「数据删除」。
--
-- ℹ️ 迁移只能新增、不能修改已应用的（见 lib.rs 顶部关于 v3 的说明）——
--    删除表必须像这样写一条新的 Down 语义迁移，而不是回头改 008。

-- ‼️ 阶段50-C.3-C：本文件**只允许一条语句**。
--    原先在下面还有两句 `DROP INDEX IF EXISTS idx_gem_coal_*`，已删除：
--    SQLite 的 `DROP TABLE` 会**连带删除该表自己的所有索引**
--    （实测该表索引为 idx_gem_coal_location / idx_gem_coal_lat_lon
--      + 1 个 sqlite_autoindex，全部属于 gem_coal_plants），
--    所以那两句是冗余的，且会让「这个迁移到底改了什么」需要多看两眼。
--    ⚠️ 不要再把它们加回来，也不要加 ALTER TABLE / VACUUM。
DROP TABLE IF EXISTS gem_coal_plants;
